function applyLang(lang){
  localStorage.setItem('site_lang', lang);
  document.documentElement.lang = lang;
  const dict = I18N[lang] || I18N.cs;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });
  document.querySelectorAll('[data-i18n-badge]').forEach(el => {
    const key = el.getAttribute('data-i18n-badge');
    if (dict[key] !== undefined) el.setAttribute('data-badge', dict[key]);
  });
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function initLang(){
  const saved = localStorage.getItem('site_lang') || 'cs';
  applyLang(saved);
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
}

document.addEventListener('DOMContentLoaded', initLang);
